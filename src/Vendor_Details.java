    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_addActionPerformed
        // TODO add your handling code here:
        
        Pattern regexPattern;
Matcher regMatcher;

// Validate contact number
regexPattern = Pattern.compile("^[7-9]\\d{9}$");
regMatcher = regexPattern.matcher(txt_contact_no.getText().toString());

if (!regMatcher.matches()) {
    // Show error message if the contact number is not valid
    JOptionPane.showMessageDialog(null, "Please enter a valid contact number starting with 7, 8, or 9 and having 10 digits.");
} else {
    // Check if any mandatory fields are left blank
     if(txt_name.getText().equals("")||txt_contact_no.getText().equals("")||txt_email.getText().equals("")||txt_address.getText().equals("")||txt_vend_type.getSelectedItem().equals("")){
        JOptionPane.showMessageDialog(null, "Please ensure no mandatory field is left blank");
    } else {
        // Insert data into the database
       String sql="insert into vendor_details(vendor_name,vendor_contact,vendor_email,vendor_address,vendor_adhaar_no,vendor_type) values('"+txt_name.getText()+"','"+txt_contact_no.getText()+"','"+txt_email.getText()+"','"+txt_address.getText()+"','"+txt_adhaar_no.getText()+"','"+txt_vend_type.getSelectedItem()+"')";
            
            String result=db.Query(sql, "Vendor details have been successfully submitted!");
            JOptionPane.showMessageDialog(null, result);
            clear(); // Call to clear the form after submission
    }
}
    }//GEN-LAST:event_btn_addActionPerformed

