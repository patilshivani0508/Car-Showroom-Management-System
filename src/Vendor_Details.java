    private void txt_vendor_idKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_vendor_idKeyReleased
        // TODO add your handling code here:
         Connection cn=null;
         Statement st=null;
    
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from vendor_details where vendor_id='"+txt_vendor_id.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            while(result.next())
            {
               txt_name.setText(result.getString("vendor_name"));
               txt_contact_no.setText(result.getString("vendor_contact"));
               txt_vend_type.setSelectedItem(result.getString("vendor_type"));
               txt_email.setText(result.getString("vendor_email"));
               txt_adhaar_no.setText(result.getString("vendor_adhaar_no"));
               txt_address.setText(result.getString("vendor_address"));
            }
            
          
         }
        catch(Exception ex)
        {
            System.out.println(ex.toString());     
        }
    }//GEN-LAST:event_txt_vendor_idKeyReleased

