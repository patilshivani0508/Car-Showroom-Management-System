    private void txt_service_idKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_service_idKeyReleased
        // TODO add your handling code here:
         Connection cn=null;
       Statement st=null;
    
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from service_and_management where service_id='"+txt_service_id.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            while(result.next())
            {
               txt_cust_name.setText(result.getString("customer_name"));
               txt_model.setText(result.getString("model"));
               txt_ser_type.setSelectedItem(result.getString("service_type"));
               txt_date.setDate(result.getDate("service_date"));
               txt_cost.setText(result.getString("service_cost"));
              
            }
            
          
         }
        catch(Exception ex)
        {
            System.out.println(ex.toString());     
        }
    }//GEN-LAST:event_txt_service_idKeyReleased

