    private void txt_order_idKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_order_idKeyReleased
        // TODO add your handling code here:
         Connection cn=null;
       Statement st=null;
    
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from vendor_order where vendor_order_id='"+txt_order_id.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            while(result.next())
            {
               txt_vendor_id.setText(result.getString("vendor_id"));
               txt_name.setText(result.getString("vendor_name"));
               txt_order_name.setText(result.getString("orders"));
               txt_quantity.setText(result.getString("quantity_ordered"));
               txt_order_date.setDate(result.getDate("ordered_date"));
               txt_delivery_date.setDate(result.getDate("delievery_date"));
            }
            
          
         }
        catch(Exception ex)
        {
            System.out.println(ex.toString());     
        }
    }//GEN-LAST:event_txt_order_idKeyReleased

