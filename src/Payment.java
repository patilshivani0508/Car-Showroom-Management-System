    private void txt_pay_idKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_pay_idKeyReleased
        // TODO add your handling code here:
        Connection cn=null;
       Statement st=null;
    
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from payment where payment_id='"+txt_pay_id.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            while(result.next())
            {
               txt_book_id.setText(result.getString("customer_id"));
               txt_cust_name.setText(result.getString("customer_name"));
               txt_car_id.setText(result.getString("car_id"));
               txt_car_name.setText(result.getString("model"));
               txt_cust_addr.setText(result.getString("customer_address"));
               txt_color.setText(result.getString("color"));
               txt_date.setDate(result.getDate("pay_date"));
               txt_discount_per.setText(result.getString("discount_per"));
               txt_total_amt.setText(result.getString("total_amount"));
               txt_pay_type.setSelectedItem(result.getString("pay_type"));
               txt_model.setText(result.getString("car_name"));
              
            }
            
          
         }
        catch(Exception ex)
        {
            System.out.println(ex.toString());     
        }
    }//GEN-LAST:event_txt_pay_idKeyReleased

