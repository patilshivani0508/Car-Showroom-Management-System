           String path="D:\\Car Showroom Management System\\Car_Showroom_Management_System\\src\\rep_payment.jrxml";
           JasperDesign design = JRXmlLoader.load(path);
    //JasperReport report = JasperCompileManager.compileReport(design);
           JasperReport jr=JasperCompileManager.compileReport(design);
           HashMap parameters=new HashMap();
           parameters.put("sdate", date1);
           parameters.put("edate", date2);
           
           JasperPrint jp=JasperFillManager.fillReport(jr, parameters, cn);
