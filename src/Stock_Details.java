    private void txt_stock_idKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_stock_idKeyReleased
        // TODO add your handling code here:
        Connection cn=null;
       Statement st=null;
    
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from stock_details where stock_id='"+txt_stock_id.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            while(result.next())
            {
               txt_model.setText(result.getString("c_model"));
               txt_date.setDate(result.getDate("stock_date"));
               txt_curr_stock.setText(result.getString("current_stock"));
               txt_car_name.setText(result.getString("car_name"));
               
              
            }
            
          
         }
        catch(Exception ex)
        {
            System.out.println(ex.toString());     
        }
    }//GEN-LAST:event_txt_stock_idKeyReleased

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
        // TODO add your handling code here:
         if(txt_model.getText().equals("")||txt_curr_stock.getText().equals("")||txt_date.getDate()==null)
        {
            JOptionPane.showMessageDialog(null, "Please ensure no mandatory field is left blank");
        }
        else
        {
            SimpleDateFormat format=new SimpleDateFormat("yyyy-MM-dd");
            String date=format.format(txt_date.getDate());
           
            
            String sql="insert into stock_details(c_model,stock_date,current_stock,car_name) values('"+txt_model.getText()+"','"+date+"','"+txt_curr_stock.getText()+"','"+txt_car_name.getText()+"')";
            
            String result=db.Query(sql, "Stock details have been successfully submitted!");
            JOptionPane.showMessageDialog(null, result);
            
        }
    }//GEN-LAST:event_btn_saveActionPerformed

