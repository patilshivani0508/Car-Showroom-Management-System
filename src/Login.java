    private void btn_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_loginActionPerformed
        // TODO add your handling code here:
        Connection cn=null;
        Statement st=null;
        try
        {
            Class.forName("com.mysql.jdbc.Driver");
            cn=DriverManager.getConnection("jdbc:mysql://localhost:3306/final_car_showroom_management_system","root","root");
            st=cn.createStatement();
            String sql="select * from sign_up where username='"+txt_username.getText()+"' and s_password='"+txt_password.getText()+"'";
            ResultSet result=st.executeQuery(sql);
            if(result.next())
            {
                this.hide();
                new Home_Page1().setVisible(true);
            }
            else
            {
                JOptionPane.showMessageDialog(null, "Login Failed");
            }
         }
        catch(Exception ex)
        {
             System.out.println(ex);   
         }
    }//GEN-LAST:event_btn_loginActionPerformed

    private void txt_usernameKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_usernameKeyPressed
        if (Character.isAlphabetic(evt.getKeyChar()) || evt.getKeyCode() == evt.VK_BACK_SPACE  || evt.getKeyCode()==32 || evt.getKeyChar() >= '0' && evt.getKeyChar() <= '9')
        {
              txt_username.setEditable(true);       
        }
        else 
        {
              txt_username.setEditable(false);     
        }

    }//GEN-LAST:event_txt_usernameKeyPressed

